// Builds a tiny, valid one-page PDF (as a data URL) so seeded applications
// have a viewable resume without shipping binary files.
export function makeSampleResumePdf(name, headline) {
  const esc = (s) => s.replace(/[\\()]/g, (c) => `\\${c}`);
  const lines = [
    [24, 760, `${name}`],
    [13, 735, headline],
    [11, 700, 'Sample resume generated by HireFlow demo data.'],
    [11, 682, 'Experience: Built production React apps, REST APIs and dashboards.'],
    [11, 664, 'Skills: JavaScript, React, Redux, Tailwind CSS, Node.js, SQL.'],
    [11, 646, 'Education: B.Tech, Computer Science.'],
  ];
  const stream = lines
    .map(([size, y, text]) => `BT /F1 ${size} Tf 60 ${y} Td (${esc(text)}) Tj ET`)
    .join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [];
  objects.forEach((body, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  return `data:application/pdf;base64,${btoa(pdf)}`;
}
